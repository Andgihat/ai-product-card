"""Промпты для генерации карточки товара.

Промпт разбит на три части:
* SYSTEM_PROMPT — роль и жёсткие правила против выдуманных данных;
* build_user_prompt — входные данные и требования к каждому полю;
* build_repair_prompt — точечная правка, если формальные лимиты нарушены.
"""

from __future__ import annotations

import json

from .schemas import ProductCard, ProductInput

SYSTEM_PROMPT = """Ты — старший контент-редактор B2B-каталога контрольно-измерительных приборов (КИП).
Ты готовишь черновик карточки товара, который контент-менеджер проверит и опубликует.

ЖЁСТКИЕ ПРАВИЛА. Их нарушение считается браком:
1. Используй только факты из блока INPUT. Запрещено добавлять характеристики, цифры,
   материалы, сертификаты, степень защиты, интерфейсы и области применения, которых там нет.
2. Не пересчитывай, не округляй и не переводи единицы измерения. Переноси значения
   в том же виде, в каком они даны во входных данных.
3. Если характеристики нет во входных данных — не придумывай её. Не включай её
   в key_specs, а в missing_data напиши, что именно нужно уточнить.
4. Если нет описания — не сочиняй назначение прибора. Опирайся только на название,
   категорию и переданные характеристики, формулируй осторожно.
5. Не выдумывай бренды, модели, артикулы, цены, сроки поставки и гарантии.
6. Не добавляй сведения о наличии на складе, доставке и скидках.

Отвечай одним JSON-объектом. Без markdown-обёрток, без комментариев и текста до/после JSON."""

OUTPUT_SCHEMA = """{
  "seo_title": "строка, 40–70 символов",
  "seo_description": "строка, 800–1200 символов с пробелами",
  "key_specs": [{"name": "название характеристики", "value": "значение из INPUT"}],
  "search_queries": ["поисковый запрос", "..."],
  "commercial_block": "строка, 3–5 предложений",
  "missing_data": ["<Характеристика>: данных нет — <что уточнить>", "..."]
}"""

FIELD_RULES = """ТРЕБОВАНИЯ К ПОЛЯМ:

seo_title
- 40–70 символов, одна строка.
- Формула: тип прибора + модель + ключевое отличие из характеристик.
- Без слов «купить», «цена», «недорого», «лучший», без CAPS и восклицательных знаков.
- Не дублируй производителя, если из-за этого превышается лимит.

seo_description
- Строго 800–1200 символов с пробелами. Это жёсткий лимит: проверь длину перед ответом.
- 5–7 предложений связного текста: что это за прибор, какую задачу решает,
  где применяется, ключевые характеристики (только из INPUT), исполнение и монтаж.
- Не пересказывай характеристики подряд. Выбери 2–3 главные, остальные не дублируй:
  полный список и так есть в key_specs.
- Без списков, markdown, заголовков и рекламных обещаний.
- Не начинай с артикула или модели, сначала — что это за прибор.
- Не повторяй название дословно более двух раз.

key_specs
- От 6 до 12 пар. Названия бери из INPUT, можно слегка нормализовать.
- Значения — дословно из INPUT, вместе с единицами измерения.
- Если во входных данных меньше 6 характеристик, верни столько, сколько есть.

search_queries
- От 3 до 5 запросов, по 2–6 слов, так, как люди реально ищут в поиске.
- Смешай коммерческие («датчик давления ПД100 купить») и уточняющие
  («датчик давления 1,6 МПа 4-20 мА») запросы.
- Только то, что покупатель вводит в поиск. Нельзя: межповерочный интервал,
  гарантию, вес, наличие, цену, артикул — это не поисковые фразы.
- Плохо: «датчик давления M20х1,5 2 года». Хорошо: «датчик давления 1,6 мпа 4-20 ма».
- Не используй бренды и модели, которых нет в INPUT.

commercial_block
- 3–5 предложений для менеджера: кто покупатель (отрасль или роль),
  какую задачу решает прибор, что проверить при подборе.
- Не пересказывай key_specs. Из характеристик упомяни не больше двух — тех,
  что реально влияют на выбор.
- Только факты из INPUT, без новых характеристик.

missing_data
- 3–7 пунктов: каких технических данных не хватает для полной карточки.
- Формат каждого пункта: «<Характеристика>: данных нет — <что уточнить>».
  Пример: «Класс точности: данных нет — уточнить у производителя».
- Только характеристики, важные для подбора прибора.
- Запрещено писать про наличие на складе, цену, срок поставки, артикул,
  гарантию, упаковку и комплектацию — это не характеристики карточки.
- Не перечисляй поля, которые уже есть в INPUT."""


def build_user_prompt(product: ProductInput) -> str:
    """Собирает пользовательское сообщение с данными товара."""
    payload = product.model_dump(exclude_none=True)
    return (
        "INPUT (единственный источник фактов):\n"
        f"{json.dumps(payload, ensure_ascii=False, indent=2)}\n\n"
        f"{FIELD_RULES}\n\n"
        "Верни JSON строго такой структуры:\n"
        f"{OUTPUT_SCHEMA}"
    )


def build_repair_prompt(
    product: ProductInput,
    card: ProductCard,
    issues: list[str],
) -> str:
    """Промпт для повторной попытки: правим только перечисленные проблемы."""
    payload = product.model_dump(exclude_none=True)
    current = card.model_dump()
    issues_text = "\n".join(f"- {issue}" for issue in issues)
    return (
        "Черновик карточки не прошёл проверку. Исправь только перечисленные проблемы,\n"
        "остальные поля оставь без изменений.\n\n"
        f"INPUT:\n{json.dumps(payload, ensure_ascii=False, indent=2)}\n\n"
        f"ТЕКУЩИЙ ЧЕРНОВИК:\n{json.dumps(current, ensure_ascii=False, indent=2)}\n\n"
        f"ПРОБЛЕМЫ:\n{issues_text}\n\n"
        f"{FIELD_RULES}\n\n"
        "Верни исправленный JSON целиком, строго такой структуры:\n"
        f"{OUTPUT_SCHEMA}"
    )
